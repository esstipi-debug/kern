"""GRAPH_LESSONS.md no puede despegarse de las memorias que dice resumir.

`documentation/GRAPH_LESSONS.md` lo genera `scripts/reflect_lessons.py` a partir
de `knowledge/graph-memory/`. Nada obligaba a regenerarlo: se podia agregar,
editar o borrar una memoria y dejar el documento diciendo otra cosa, y el unico
sintoma habria sido un lector confiando en un resumen viejo.

POR QUE ESTO ES UN TEST Y NO UN PASO SUELTO DE tests.yml
--------------------------------------------------------
`python scripts/reflect_lessons.py --check` completo NO puede correr en un
runner de GitHub, y medirlo antes de cablearlo evito dejar la CI en rojo
permanente. Dos motivos, los dos verificados el 2026-08-24:

1. El script invoca el binario `graphify` (paquete `graphifyy`), que no esta
   declarado en requirements-dev.txt ni en pyproject: lo instala el hook de
   SessionStart en la maquina del dev. En la CI no existe, y `subprocess.run`
   con un ejecutable ausente levanta FileNotFoundError, no un exit code.
2. Reflect resuelve las memorias contra la UNION del grafo de libros y el de
   codigo, y el de codigo es `graphify-out/graph.json` -- 17 MB, gitignoreado,
   reconstruido por ese mismo hook. Sin el, el documento se regenera podado.
   Medido: con la union da 69 lineas (identico al commiteado), solo con libros
   da 41. O sea `--check` en la CI devolveria 1 SIEMPRE, por una razon que no
   tiene nada que ver con que el documento este al dia.

Lo que si es verificable con lo que hay commiteado es el encabezado: el conteo
de memorias y el desglose de outcomes salen enteros de `knowledge/graph-memory/`
y son identicos en las dos versiones del documento. Esa es exactamente la deriva
que importa -- "el documento dice resumir N memorias y hay M" -- y se chequea
aca sin dependencias, asi que corre en la CI dentro del paso de pytest y tambien
en cada corrida local.

El `--check` completo tambien corre, cuando la maquina tiene con que. En la CI
se saltea con el motivo escrito; no se calla.
"""
from __future__ import annotations

import collections
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

RAIZ = Path(__file__).resolve().parents[1]
MEMORIAS = RAIZ / "knowledge" / "graph-memory"
DOC = RAIZ / "documentation" / "GRAPH_LESSONS.md"
SCRIPT = RAIZ / "scripts" / "reflect_lessons.py"
GRAFO_CODIGO = RAIZ / "graphify-out" / "graph.json"

#: `_Auto-generated by ... from 25 session memories in ..._`
_TOTAL = re.compile(r"from\s+(\d+)\s+session memories")

#: `- 20 useful . 0 dead ends . 3 corrected . 2 unmarked`. El separador es un
#: caracter no-ASCII del documento y no hace falta nombrarlo para leer la linea.
_RESUMEN = re.compile(
    r"(\d+)\s+useful\D+(\d+)\s+dead ends?\D+(\d+)\s+corrected\D+(\d+)\s+unmarked"
)


def _conteos(directorio: Path) -> dict[str, int]:
    """Lo que dice el store de memorias, contado de los archivos.

    El vocabulario de outcomes NO se hardcodea: `useful`, `corrected` y "sin
    campo" se cuentan por nombre y TODO LO DEMAS cae en dead ends. Asi, si
    aparece una memoria con un valor que este test no conocia, el numero deja de
    coincidir con el documento y alguien lo mira -- en vez de que el test elija
    en silencio un balde y apruebe.
    """
    archivos = [p for p in sorted(directorio.glob("*.md")) if p.name.lower() != "readme.md"]
    c: collections.Counter[str] = collections.Counter()
    for p in archivos:
        m = re.search(r'^outcome:\s*"?([^"\n]*)"?\s*$', p.read_text(encoding="utf-8"), re.MULTILINE)
        valor = (m.group(1).strip() if m else "")
        if not valor:
            c["unmarked"] += 1
        elif valor in ("useful", "corrected"):
            c[valor] += 1
        else:
            c["dead ends"] += 1
    return {
        "total": len(archivos),
        "useful": c["useful"],
        "dead ends": c["dead ends"],
        "corrected": c["corrected"],
        "unmarked": c["unmarked"],
    }


def _del_documento(texto: str) -> dict[str, int]:
    """Lo que el documento AFIRMA sobre el store."""
    total = _TOTAL.search(texto)
    assert total, (
        "el encabezado de GRAPH_LESSONS.md ya no dice 'from N session memories'; este "
        "test no lo sabe leer y prefiere fallar antes que aprobarlo a ciegas"
    )
    resumen = _RESUMEN.search(texto)
    assert resumen, (
        "la linea de Summary de GRAPH_LESSONS.md ya no tiene la forma "
        "'N useful ... N dead ends ... N corrected ... N unmarked'; puede que "
        "`graphify reflect` haya agregado una categoria nueva. Revisar antes de "
        "aflojar esta expresion."
    )
    u, d, c, s = (int(g) for g in resumen.groups())
    return {
        "total": int(total.group(1)),
        "useful": u,
        "dead ends": d,
        "corrected": c,
        "unmarked": s,
    }


# --- 1. el documento y el store dicen lo mismo -------------------------------


def test_el_documento_resume_las_memorias_que_hay():
    """EL TEST QUE IMPORTA.

    Agregar, borrar o re-marcar una memoria sin regenerar el documento lo deja
    afirmando un conteo que ya no es cierto. A partir de aca, falla.
    """
    afirmado = _del_documento(DOC.read_text(encoding="utf-8"))
    real = _conteos(MEMORIAS)
    assert afirmado == real, (
        f"GRAPH_LESSONS.md afirma {afirmado} y knowledge/graph-memory/ tiene {real}. "
        f"Regenerar con: python scripts/reflect_lessons.py"
    )


def test_las_partes_cierran_con_el_total():
    """Un desglose que no suma el total significa que el documento y el store se
    despegaron aunque cada numero suelto parezca razonable."""
    real = _conteos(MEMORIAS)
    partes = real["useful"] + real["dead ends"] + real["corrected"] + real["unmarked"]
    assert partes == real["total"], f"el desglose suma {partes} y hay {real['total']} memorias"


def test_el_conteo_muerde_de_verdad(tmp_path):
    """Un gate solo acredita si la salida cambia entre dos insumos.

    Sin esta contraprueba, el test de arriba pasaria igual con un `_conteos` que
    devolviera siempre lo que dice el documento.
    """
    real = _conteos(MEMORIAS)

    (tmp_path / "README.md").write_text("no es una memoria\n", encoding="utf-8")
    (tmp_path / "a.md").write_text('---\noutcome: "useful"\n---\n', encoding="utf-8")
    (tmp_path / "b.md").write_text('---\noutcome: "corrected"\n---\n', encoding="utf-8")
    (tmp_path / "c.md").write_text('---\ndate: "hoy"\n---\n', encoding="utf-8")
    (tmp_path / "d.md").write_text('---\noutcome: "dead_end"\n---\n', encoding="utf-8")

    inventado = _conteos(tmp_path)
    assert inventado == {
        "total": 4, "useful": 1, "dead ends": 1, "corrected": 1, "unmarked": 1
    }, inventado
    assert inventado != real, "el contador devuelve lo mismo para dos stores distintos"

    # Y el lado del documento tambien tiene que moverse.
    otro = _del_documento("from 99 session memories\n- 1 useful X 2 dead ends X 3 corrected X 4 unmarked")
    assert otro == {"total": 99, "useful": 1, "dead ends": 2, "corrected": 3, "unmarked": 4}, otro


# --- 2. el --check completo, cuando la maquina tiene con que ------------------


def test_el_check_completo_cuando_estan_las_herramientas():
    """`reflect_lessons.py --check` de verdad: regenera y compara byte a byte.

    Cubre lo que el encabezado no puede -- que el CUERPO del documento siga
    resolviendo contra el grafo. Necesita el binario `graphify` y el grafo de
    codigo, que en un runner de GitHub no existen (ver el docstring del modulo).
    Cuando faltan, se saltea diciendo cual falta: un gate que se calla es peor
    que no tenerlo, porque se parece a "todo limpio".
    """
    faltan = []
    if shutil.which("graphify") is None:
        faltan.append("el binario `graphify` (uv tool install graphifyy)")
    if not GRAFO_CODIGO.is_file():
        faltan.append("graphify-out/graph.json (lo reconstruye el hook de SessionStart)")
    if faltan:
        pytest.skip(
            "no corre el --check completo, falta: " + "; ".join(faltan)
            + ". El encabezado igual quedo verificado por los tests de arriba."
        )

    proc = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"],
        cwd=RAIZ, capture_output=True, text=True,
    )
    assert proc.returncode == 0, (
        "GRAPH_LESSONS.md quedo viejo respecto de las memorias y del grafo. "
        "Regenerar con: python scripts/reflect_lessons.py\n"
        + (proc.stdout or "") + (proc.stderr or "")
    )
